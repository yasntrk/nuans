// Generates the launcher icon and the splash mark from `NuansMark`.
//
// Run with:
//   flutter test tools/branding/generate_icons.dart
//
// A generator rather than a folder of hand-made bitmaps, for the reason this
// repository uses generators everywhere else: the mark is then reviewable as
// code, a change to it cannot leave one density behind, and nobody has to own
// a design file that is not in the repository.
//
// It runs under `flutter test` because encoding a PNG needs `dart:ui`, which
// only exists inside the engine. It lives outside `test/` so the ordinary
// suite does not rewrite checked-in assets as a side effect of running.

import 'dart:io';
import 'dart:ui';

import 'package:flutter_test/flutter_test.dart';
import 'package:nuans/core/branding/nuans_mark.dart';

/// Android's density buckets, as multiples of mdpi.
const _densities = <String, double>{
  'mdpi': 1,
  'hdpi': 1.5,
  'xhdpi': 2,
  'xxhdpi': 3,
  'xxxhdpi': 4,
};

/// The adaptive icon's canvas, in dp. Android masks it down to a guaranteed
/// 72 dp, so the mark is inset well inside that.
const _adaptiveDp = 108.0;

/// How much of the adaptive canvas the mark may use.
///
/// The outer 18 dp on each edge belongs to the launcher's mask and its
/// parallax; anything drawn there is a gamble on which launcher is installed.
const _adaptiveInset = 0.72;

/// The legacy icon, for anything that ignores the adaptive one.
const _legacyDp = 48.0;

/// The splash mark, in dp. Large enough to read as a mark on a phone screen
/// rather than a speck, small enough not to become a hero image on a tablet.
const _splashDp = 144.0;

Future<void> _writePng(
  String path,
  int pixels, {
  required bool withGround,
  double inset = 1,
}) async {
  final recorder = PictureRecorder();
  final canvas = Canvas(recorder);
  final size = Size(pixels.toDouble(), pixels.toDouble());
  NuansMark.paint(canvas, size, withGround: withGround, inset: inset);
  final picture = recorder.endRecording();
  final image = await picture.toImage(pixels, pixels);
  final data = await image.toByteData(format: ImageByteFormat.png);
  if (data == null) {
    throw StateError('the engine encoded no bytes for $path');
  }
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsBytesSync(data.buffer.asUint8List());
  image.dispose();
  picture.dispose();
  stdout.writeln('wrote $path (${pixels}x$pixels)');
}

String _hex(Color colour) {
  final rgb = colour.toARGB32() & 0xFFFFFF;
  return '#${rgb.toRadixString(16).padLeft(6, '0').toUpperCase()}';
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  const res = 'android/app/src/main/res';

  test('the adaptive foreground stays inside the circle Android guarantees',
      () {
    // Of the 108 dp canvas, only the middle 72 dp is certain to survive the
    // launcher's mask, and a round mask inscribes that square as a circle. The
    // corners of the mark are what reach furthest, so they are what is checked.
    const canvas = Size(_adaptiveDp, _adaptiveDp);
    final bounds = NuansMark.boundsFor(canvas, inset: _adaptiveInset);
    const safeRadius = _adaptiveDp * 72 / 108 / 2;
    final corner = Offset(bounds.width / 2, bounds.height / 2).distance;
    expect(
      corner,
      lessThan(safeRadius),
      reason: 'the mark reaches ${corner.toStringAsFixed(1)} dp from the '
          'centre; the mask may cut past ${safeRadius.toStringAsFixed(1)}',
    );
  });

  test('launcher icons, splash mark and the resources that point at them',
      () async {
    for (final entry in _densities.entries) {
      final bucket = entry.key;
      final scale = entry.value;
      await _writePng(
        '$res/mipmap-$bucket/ic_launcher_foreground.png',
        (_adaptiveDp * scale).round(),
        withGround: false,
        inset: _adaptiveInset,
      );
      await _writePng(
        '$res/mipmap-$bucket/ic_launcher.png',
        (_legacyDp * scale).round(),
        withGround: true,
      );
      await _writePng(
        '$res/drawable-$bucket/splash_mark.png',
        (_splashDp * scale).round(),
        withGround: false,
      );
    }

    // minSdk is 29, so every device this installs on masks the icon itself.
    // The adaptive icon is the real one; the legacy bitmap above is a fallback
    // nothing in the supported range actually reaches for.
    File('$res/mipmap-anydpi-v26/ic_launcher.xml')
      ..parent.createSync(recursive: true)
      ..writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/branding/generate_icons.dart; do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
''');

    File('$res/values/ic_launcher_background.xml')
      ..parent.createSync(recursive: true)
      ..writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/branding/generate_icons.dart; do not edit. -->
<resources>
    <color name="ic_launcher_background">${_hex(NuansMark.ground)}</color>
</resources>
''');

    // The splash is the same ground with the same mark on it, so the first
    // thing drawn after the launcher is the thing that was tapped. One file
    // for both themes, with no -night twin: the ground is a dark neutral
    // already, so a night variant would have nothing to change, and a light
    // splash would mean the screen flashing white before Flutter draws.
    File('$res/drawable/launch_background.xml')
      ..parent.createSync(recursive: true)
      ..writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/branding/generate_icons.dart; do not edit. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/ic_launcher_background"/>
    <item>
        <bitmap
            android:gravity="center"
            android:src="@drawable/splash_mark"/>
    </item>
</layer-list>
''');
    stdout.writeln('wrote the adaptive icon, its colour and the splash');
  });
}
