"""Generates lib/l10n/app_tr.arb and lib/l10n/app_en.arb from strings.py.

Run:  python3 -I tools/l10n/generate.py
Check only (CI):  python3 -I tools/l10n/generate.py --check
"""

import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from strings import STRINGS  # noqa: E402

TEMPLATE_LOCALE = "en"


# `{name}` or `{name, select, ...}`, but not a branch body like
# `slight{biraz daha açık}`.
PLACEHOLDER = re.compile(r"\{\s*(\w+)\s*[,}]")


def placeholders_in(message):
    """The placeholder names a message references.

    Exact for a plain message. For an ICU select or plural message it also picks
    up single-word branch bodies - `other{lighter}` is indistinguishable from a
    placeholder without a real ICU parser - so the caller only uses it for the
    checks where that does not matter.
    """
    return set(PLACEHOLDER.findall(message))


def is_icu(message):
    return "select," in message or "plural," in message


def escape_for_icu(message):
    """Escapes a message for an ARB file read with ICU escaping enabled.

    `l10n.yaml` sets `use-escaping: true`, which is the right setting for a
    project that uses ICU select and plural: without it there is no way to put a
    literal brace in a message. The cost is that a single quote becomes the
    escape character, so every real apostrophe has to be doubled.

    Doing it here rather than in the string table means the table stays readable
    - English possessives and Turkish suffixes like `Ayarlar'dan` are written
    normally - and nobody has to remember the rule. Forgetting it is not a
    subtle bug: `flutter gen-l10n` refuses to build.
    """
    return message.replace("'", "''")


def build(locale):
    index = 0 if locale == "tr" else 1
    arb = {
        "@@locale": locale,
        "@@context": (
            "Generated by tools/l10n/generate.py from tools/l10n/strings.py. "
            "Do not edit by hand: edit the generator's string table instead, "
            "which defines both languages side by side so a key can never "
            "exist in one file and not the other."
        ),
    }
    for key, (tr, en, description, placeholders) in STRINGS.items():
        arb[key] = escape_for_icu(tr if index == 0 else en)
        meta = {"description": description}
        if placeholders:
            meta["placeholders"] = placeholders
        arb["@" + key] = meta
    return arb


def validate():
    """Checks the table for the mistakes that reach users.

    The strongest check is the last one: a placeholder declared once but used in
    only one language produces a sentence with a hole in it, in that language
    only, which is exactly the kind of bug that ships.
    """
    problems = []
    for key, entry in STRINGS.items():
        if not re.fullmatch(r"[a-z][A-Za-z0-9]*", key):
            problems.append(f"{key}: key must be lowerCamelCase")
        tr, en, description, placeholders = entry
        if not tr or not en:
            problems.append(f"{key}: both languages must be present")
        if not description:
            problems.append(f"{key}: every message needs a description")

        declared = set(placeholders or {})
        used_tr = placeholders_in(tr)
        used_en = placeholders_in(en)

        # Undeclared references can only be checked on plain messages: in an ICU
        # message a one-word branch body looks the same to a regex, and
        # gen-l10n parses those properly at build time anyway.
        if not is_icu(tr) and not is_icu(en):
            undeclared = (used_tr | used_en) - declared
            if undeclared:
                problems.append(
                    f"{key}: references undeclared {sorted(undeclared)}"
                )

        if declared:
            unused = declared - used_tr - used_en
            if unused:
                problems.append(f"{key}: declares unused {sorted(unused)}")
            # Every declared placeholder must appear in both languages.
            missing_tr = declared - used_tr
            missing_en = declared - used_en
            if missing_tr or missing_en:
                problems.append(
                    f"{key}: declared placeholder missing from "
                    f"tr {sorted(missing_tr)}, en {sorted(missing_en)}"
                )
    return problems


def main():
    check_only = "--check" in sys.argv
    problems = validate()
    if problems:
        print(f"{len(problems)} problem(s) in the string table:")
        for problem in problems:
            print("  -", problem)
        return 1

    root = pathlib.Path(__file__).resolve().parents[2]
    out = root / "lib" / "l10n"
    out.mkdir(parents=True, exist_ok=True)
    changed = False
    for locale in ("tr", "en"):
        path = out / f"app_{locale}.arb"
        rendered = json.dumps(build(locale), indent=2, ensure_ascii=False) + "\n"
        existing = path.read_text() if path.exists() else None
        if existing != rendered:
            changed = True
            if not check_only:
                path.write_text(rendered)
        print(
            f"{'would update' if check_only and existing != rendered else 'wrote'}"
            f" lib/l10n/app_{locale}.arb"
        )

    tr = build("tr")
    en = build("en")
    tr_keys = {k for k in tr if not k.startswith("@")}
    en_keys = {k for k in en if not k.startswith("@")}
    assert tr_keys == en_keys, "key sets diverged, which the generator prevents"
    print(f"\n{len(tr_keys)} messages, both locales, keys identical by construction")
    if check_only and changed:
        print("the generated files are out of date; run the generator")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
